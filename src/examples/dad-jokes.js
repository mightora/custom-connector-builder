import { buildYaml } from '../builders/yaml-builder.js'

export const dadJokesExample = {
  name: 'Dad Jokes (Static C#)',
  description: 'Returns a static dad joke from C# without calling any external API.',
  config: {
    connectorName: 'Dad Jokes',
    description: 'Returns a static dad joke response built entirely in C#.',
    host: 'api.local',
    basePath: '/',
    authType: 'none',
    actions: [
      {
        operationId: 'GetRandomDadJoke',
        summary: 'Get a random dad joke',
        description: 'Retrieves a random dad joke from the API.',
        method: 'get',
        path: '/',
        parameters: [],
        responses: {
          '200': {
            description: 'Success',
            schema: {
              type: 'object',
              properties: {
                id: { type: 'string' },
                joke: { type: 'string' },
                status: { type: 'integer' }
              }
            }
          }
        }
      }
    ]
  },

  generateYaml() {
    return buildYaml(this.config)
  },

  generateCSharp() {
    return `// Dad Jokes (Static C# Response) - C# Script Example
// Generated by Custom Connector Builder
// https://tools.mightora.io/custom-connector-builder
//
// This example shows how to return a static JSON response directly in C#.
// No external API is called — all data is returned from within the script.

public class Script : ScriptBase
{
    public override async Task<HttpResponseMessage> ExecuteAsync()
    {
        // Build a static joke response entirely in C# — no external API call needed.
        var result = new JObject
        {
            ["id"]     = "static-001",
            ["joke"]   = "Why don't scientists trust atoms? Because they make up everything!",
            ["status"] = 200
        };

        var response = new HttpResponseMessage(HttpStatusCode.OK)
        {
            Content = CreateJsonContent(result.ToString())
        };

        return response;
    }
}
`
  }
}
