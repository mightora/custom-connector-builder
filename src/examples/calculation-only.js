import { buildYaml } from '../builders/yaml-builder.js'

export const calculationOnlyExample = {
  name: 'Calculation Helper',
  description: 'No external API. Performs calculations like VAT and percentages.',
  config: {
    connectorName: 'Calculation Helper',
    description: 'Perform common calculations without calling an external API.',
    host: 'localhost',
    basePath: '/',
    authType: 'none',
    actions: [
      {
        operationId: 'CalculateVAT',
        summary: 'Calculate VAT',
        description: 'Calculate VAT on a given amount.',
        method: 'post',
        path: '/calculate-vat',
        parameters: [
          {
            name: 'amount',
            in: 'body',
            type: 'number',
            required: true,
            description: 'The amount to calculate VAT on'
          },
          {
            name: 'vatRate',
            in: 'body',
            type: 'number',
            required: false,
            description: 'VAT rate percentage (default 20)'
          }
        ],
        responses: {
          '200': {
            description: 'Success',
            schema: {
              type: 'object',
              properties: {
                vatAmount: { type: 'number' },
                totalAmount: { type: 'number' },
                message: { type: 'string' }
              }
            }
          }
        }
      }
    ]
  },

  generateYaml() {
    return buildYaml(this.config)
  },

  generateCSharp() {
    return `// Calculation Helper - CalculateVAT
// Generated by Custom Connector Builder
// https://tools.mightora.io/custom-connector-builder

public class Script : ScriptBase
{
    public override async Task<HttpResponseMessage> ExecuteAsync()
    {
        // Read the incoming request body
        var contentAsString = await this.Context.Request.Content
            .ReadAsStringAsync().ConfigureAwait(false);

        JObject input;
        try
        {
            input = JObject.Parse(contentAsString);
        }
        catch
        {
            return new HttpResponseMessage(HttpStatusCode.BadRequest)
            {
                Content = CreateJsonContent("{\\"error\\": \\"Invalid JSON in request body\\"}")
            };
        }

        // Extract parameters
        var amount = input["amount"]?.Value<decimal>() ?? 0m;
        var vatRate = input["vatRate"]?.Value<decimal>() ?? 20m;

        // Validate inputs
        if (amount <= 0)
        {
            return new HttpResponseMessage(HttpStatusCode.BadRequest)
            {
                Content = CreateJsonContent("{\\"error\\": \\"amount must be greater than zero\\"}")
            };
        }

        if (vatRate < 0 || vatRate > 100)
        {
            return new HttpResponseMessage(HttpStatusCode.BadRequest)
            {
                Content = CreateJsonContent("{\\"error\\": \\"vatRate must be between 0 and 100\\"}")
            };
        }

        // Perform calculation
        var vatAmount = Math.Round(amount * (vatRate / 100m), 2);
        var totalAmount = Math.Round(amount + vatAmount, 2);

        // Build response
        var result = new JObject
        {
            ["vatAmount"]   = vatAmount,
            ["totalAmount"] = totalAmount,
            ["message"]     = $"VAT at {vatRate}% on {amount:C} = {vatAmount:C}. Total = {totalAmount:C}"
        };

        var response = new HttpResponseMessage(HttpStatusCode.OK)
        {
            Content = CreateJsonContent(result.ToString())
        };
        return response;
    }
}
`
  }
}
