/**
 * Generates C# Script code for Power Platform custom connector policy templates.
 * @param {object} config
 * @param {string} config.connectorName
 * @param {string} config.operationId
 * @param {Array}  config.inputs  - [{ name, type }]
 * @param {string} config.csharpLogic - custom logic snippet
 * @returns {string} C# code string
 */
export function buildCSharp(config) {
  const {
    connectorName = 'My Connector',
    operationId = 'ExecuteOperation',
    inputs = [],
    csharpLogic = ''
  } = config

  const extractInputs = inputs
    .map((p) => {
      const varName = toCamelCase(p.name || 'input')
      const type = toCSharpType(p.type || 'string')
      if (type === 'decimal') {
        return `            var ${varName} = input["${p.name}"]?.Value<decimal>() ?? 0m;`
      } else if (type === 'DateTime') {
        return `            var ${varName} = DateTime.Parse(input["${p.name}"]?.Value<string>() ?? DateTime.Now.ToString("o"));`
      } else if (type === 'bool') {
        return `            var ${varName} = input["${p.name}"]?.Value<bool>() ?? false;`
      } else {
        return `            var ${varName} = input["${p.name}"]?.Value<string>() ?? "";`
      }
    })
    .join('\n')

  const customLogicBlock = csharpLogic.trim()
    ? csharpLogic
        .split('\n')
        .map((l) => `            ${l}`)
        .join('\n')
    : `            // TODO: Add your custom logic here
            var result = new JObject
            {
                ["message"] = "Success"
            };`

  return `// ${connectorName} - ${operationId}
// Generated by Custom Connector Builder
// https://tools.mightora.io/custom-connector-builder

public class Script : ScriptBase
{
    public override async Task<HttpResponseMessage> ExecuteAsync()
    {
        // Read the incoming request body
        var contentAsString = await this.Context.Request.Content.ReadAsStringAsync().ConfigureAwait(false);
        JObject input;
        try
        {
            input = JObject.Parse(contentAsString);
        }
        catch
        {
            input = new JObject();
        }

        // Extract input parameters
${extractInputs || '            // No parameters defined'}

        // Custom logic
${customLogicBlock}

        // Build and return the response
        var responseContent = result.ToString();
        var response = new HttpResponseMessage(HttpStatusCode.OK)
        {
            Content = CreateJsonContent(responseContent)
        };
        return response;
    }
}
`
}

function toCamelCase(str) {
  return str
    .replace(/[^a-zA-Z0-9]+(.)/g, (_, chr) => chr.toUpperCase())
    .replace(/^[A-Z]/, (c) => c.toLowerCase())
}

function toCSharpType(type) {
  switch (type) {
    case 'number':
    case 'integer':
      return 'decimal'
    case 'boolean':
      return 'bool'
    case 'date':
    case 'datetime':
      return 'DateTime'
    default:
      return 'string'
  }
}
